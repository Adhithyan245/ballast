"""Generate web/lib/generated.js from the Python study code (prompt templates, scorer weights),
copy the shared engine into the static site, and write the parity fixtures the Node check uses.

    python scripts/build_web.py
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from aisci import prompts  # noqa: E402
from aisci.cache import Cache  # noqa: E402
from aisci.parsing import ParseError, parse_response  # noqa: E402

WEB = ROOT / "web"


def main():
    scorer = json.loads((ROOT / "demo" / "scorer_weights.json").read_text(encoding="utf-8"))
    gen = {
        # str.format templates use {{ }} for literal braces; the JS filler uses single braces.
        "closedTemplate": prompts.CLOSED_TEMPLATE.replace("{{", "{").replace("}}", "}"),
        "contextTemplate": prompts.CONTEXT_TEMPLATE.replace("{{", "{").replace("}}", "}"),
        "pushbackTemplate": prompts.PUSHBACK_TEMPLATE,
        "scorer": scorer,
    }
    js = ("// Generated by scripts/build_web.py from the Python study code. Do not edit.\n"
          "var BALLAST_GENERATED = " + json.dumps(gen, indent=1) + ";\n"
          "if (typeof module !== \"undefined\") module.exports = BALLAST_GENERATED;\n")
    (WEB / "lib" / "generated.js").write_text(js, encoding="utf-8")
    for f in ("generated.js", "ballast.js"):
        shutil.copy(WEB / "lib" / f, WEB / f)          # served to the browser
    shutil.copy(ROOT / "demo" / "data.json", WEB / "study-data.json")
    # parity fixtures: every cached main-study reply with Python's parse verdict
    fx = []
    for rec in Cache().iter_records():
        if rec.get("sample") != "main":
            continue
        req = rec["condition"].startswith("context")
        try:
            p = parse_response(rec.get("text"), require_quotes=req)
            fx.append({"t": rec.get("text"), "q": req, "ok": True, "a": p.answer, "c": p.confidence,
                       "n": len(p.quotes) if p.quotes is not None else None})
        except ParseError:
            fx.append({"t": rec.get("text"), "q": req, "ok": False})
    (WEB / "tests").mkdir(exist_ok=True)
    (WEB / "tests" / "parse_fixtures.json").write_text(json.dumps(fx), encoding="utf-8")
    # prompt fixtures: Python-built prompts for a few real questions
    from aisci import data
    items = data.load()
    pf = []
    for q in data.load_sample("main")[:5]:
        it = items[q]
        pf.append({"question": it.question, "abstract": it.abstract,
                   "closed": prompts.build_prompt("closed", it.question),
                   "context": prompts.build_prompt("context", it.question, it.abstract),
                   "push_no": prompts.build_pushback("no")})
    (WEB / "tests" / "prompt_fixtures.json").write_text(json.dumps(pf), encoding="utf-8")
    print(f"generated web/lib/generated.js; {len(fx)} parse fixtures; {len(pf)} prompt fixtures")


if __name__ == "__main__":
    main()
